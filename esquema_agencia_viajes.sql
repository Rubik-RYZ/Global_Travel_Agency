CREATE TABLE vuelos (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    numero_vuelo       TEXT NOT NULL,
    salida             TIMESTAMPTZ NOT NULL,
    llegada            TIMESTAMPTZ NOT NULL,
    precio             NUMERIC(12,2) NOT NULL,
    moneda             VARCHAR(3) NOT NULL,
    cupos_totales      INT NOT NULL,
    cupos_disponibles  INT NOT NULL,
    referencia_externa TEXT,
    destino            VARCHAR(3) NOT NULL,
    origen             VARCHAR(3) NOT NULL,
    proveedor_id       BIGINT NOT NULL,
    CONSTRAINT vuelos_cupos_disponibles_lte_totales
        CHECK (cupos_disponibles <= cupos_totales),
    CONSTRAINT vuelos_cupos_disponibles_no_negativos
        CHECK (cupos_disponibles >= 0),
    CONSTRAINT vuelos_cupos_totales_no_negativos
        CHECK (cupos_totales >= 0),
    CONSTRAINT vuelos_llegada_posterior_salida CHECK (llegada > salida),
    CONSTRAINT vuelos_origen_distinto_destino
        CHECK (NOT (origen::text = destino::text)),
    CONSTRAINT vuelos_precio_no_negativo CHECK (precio >= 0)
);

